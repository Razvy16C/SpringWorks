const blockSheet = new Image();
blockSheet.src = 'blocks-tileset.png';

// x, y = centre of the body; w, h = its size; angle in radians
function drawBlock(ctx, name, x, y, w, h = w, angle = 0) {
  const [sx, sy] = BLOCKS[name];
  ctx.save();
  ctx.translate(x, y);
  ctx.rotate(angle);
  ctx.drawImage(blockSheet, sx, sy, BLOCK_SIZE, BLOCK_SIZE, -w / 2, -h / 2, w, h);
  ctx.restore();
}

// For long beams: repeats the texture instead of stretching it.
// The texture is scaled to the beam's height (h).
function drawBeam(ctx, name, x, y, w, h, angle = 0) {
  const [sx, sy] = BLOCKS[name];
  ctx.save();
  ctx.translate(x, y);
  ctx.rotate(angle);
  for (let dx = 0; dx < w; dx += h) {
    const part = Math.min(h, w - dx);
    ctx.drawImage(blockSheet, sx, sy, BLOCK_SIZE * part / h, BLOCK_SIZE,
                  -w / 2 + dx, -h / 2, part, h);
  }
  ctx.restore();
}
